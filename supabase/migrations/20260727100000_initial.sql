create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  company text not null,
  segment text not null default '',
  city text not null default '',
  uf text not null default '',
  region text not null default '',
  priority text not null default '',
  email text not null default '',
  email_source text not null default '',
  can_send boolean not null default false,
  commercial_profile text not null default '',
  regional_market text not null default '',
  applications text not null default '',
  suggested_products text not null default '',
  differentiation text not null default '',
  personalization_basis text not null default '',
  confidence text not null default '',
  human_review text not null default '',
  subject text not null default '',
  greeting text not null default '',
  initial_body text not null default '',
  followup1_body text not null default '',
  followup2_body text not null default '',
  cta text not null default '',
  privacy_footer text not null default '',
  campaign_status text not null default 'Aguardando aprovação',
  approved boolean not null default false,
  approved_at timestamptz,
  sent_at timestamptz,
  followup1_at timestamptz,
  followup2_at timestamptz,
  response text not null default '',
  response_class text not null default '',
  opted_out boolean not null default false,
  bounce text not null default '',
  notes text not null default '',
  regional_source text not null default '',
  specific_source text not null default '',
  research_prompt text not null default '',
  version text not null default '',
  stage smallint not null default 0 check (stage between 0 and 3),
  replied boolean not null default false,
  paused boolean not null default false,
  dry_run_generated boolean not null default false,
  message_ids jsonb not null default '[]'::jsonb,
  research jsonb,
  source_type text not null default '',
  cnpj text not null default '',
  cnae text not null default '',
  cnae_description text not null default '',
  mx_validated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()

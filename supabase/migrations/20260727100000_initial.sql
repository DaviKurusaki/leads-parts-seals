create index if not exists events_type_at_idx
  on public.events (type, at desc);

create index if not exists events_lead_at_idx
  on public.events (lead_id, at desc);

create table if not exists public.processed_imap_uids (
  mailbox text not null default 'INBOX',
  uid text not null,
  processed_at timestamptz not null default now(),
  primary key (mailbox, uid)
);

create table if not exists public.email_jobs (
  id uuid primary key default gen_random_uuid(),
  lead_id bigint not null references public.leads(id) on delete cascade,
  stage smallint not null check (stage between 0 and 2),
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'sent', 'failed', 'cancelled')),
  available_at timestamptz not null default now(),
  locked_at timestamptz,
  locked_by text,
  attempts integer not null default 0,
  message_id text,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (lead_id, stage)
);

create index if not exists email_jobs_claim_idx
  on public.email_jobs (status, available_at, created_at)
  where status in ('pending', 'failed');

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists campaigns_touch_updated_at on public.campaigns;
create trigger campaigns_touch_updated_at
before update on public.campaigns
for each row execute function public.touch_updated_at();

drop trigger if exists leads_touch_updated_at on public.leads;
create trigger leads_touch_updated_at
before update on public.leads
for each row execute function public.touch_updated_at();

drop trigger if exists active_clients_touch_updated_at on public.active_clients;
create trigger active_clients_touch_updated_at
before update on public.active_clients
for each row execute function public.touch_updated_at();

drop trigger if exists email_jobs_touch_updated_at on public.email_jobs;
create trigger email_jobs_touch_updated_at
before update on public.email_jobs
for each row execute function public.touch_updated_at();

create or replace function public.sync_leads_identity()
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  next_value bigint;
begin
  select coalesce(max(id), 0) + 1 into next_value from public.leads;
  perform setval(
    pg_get_serial_sequence('public.leads', 'id'),
    greatest(next_value, 1),
    false
  );
  return next_value;
end;
$$;

create or replace function public.claim_next_email_job(worker_id text)
returns setof public.email_jobs
language plpgsql
security invoker
set search_path = ''
as $$
begin
  return query
  with candidate as (
    select job.id
    from public.email_jobs as job
    where job.status in ('pending', 'failed')
      and job.available_at <= now()
      and (
        job.locked_at is null
        or job.locked_at < now() - interval '15 minutes'
      )
    order by job.available_at, job.created_at
    for update skip locked
    limit 1
  )
  update public.email_jobs as job
  set
    status = 'processing',
    locked_at = now(),
    locked_by = worker_id,
    attempts = job.attempts + 1
  from candidate
  where job.id = candidate.id
  returning job.*;
end;
$$;


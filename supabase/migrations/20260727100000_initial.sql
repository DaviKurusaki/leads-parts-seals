  on public.leads (lower(email))
  where email <> '';

create index if not exists leads_campaign_queue_idx
  on public.leads (approved, paused, opted_out, replied, stage, priority, confidence, id);

create index if not exists leads_state_idx
  on public.leads (uf, campaign_status);

create index if not exists leads_cnpj_idx
  on public.leads (cnpj)
  where cnpj <> '';

create table if not exists public.active_clients (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  legal_name text not null default '',
  city text not null default '',
  cnpj text not null default '',
  email text not null default '',
  site text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists active_clients_cnpj_unique
  on public.active_clients (cnpj)
  where cnpj <> '';

create index if not exists active_clients_email_idx
  on public.active_clients (lower(email))
  where email <> '';

create table if not exists public.events (
  id uuid primary key default gen_random_uuid(),
  type text not null,
  at timestamptz not null default now(),
  lead_id bigint references public.leads(id) on delete set null,
  details jsonb not null default '{}'::jsonb
